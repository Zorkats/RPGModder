using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using System.Diagnostics.CodeAnalysis;
using System.Text;

namespace RPGModder.Core.Merge;

/// <summary>
/// The text form of <c>js/plugins.js</c> (seam 11.1): a prefix that names <c>$plugins</c> and ends with <c>=</c>,
/// one strict JSON array, then only white space and an optional <c>;</c>. The array is read as JSON, never as
/// script and never line by line (GR-C11); prefix and suffix are kept byte for byte.
/// </summary>
internal sealed record PluginListText(string Prefix, JArray Entries, string Suffix)
{
    /// <summary>What the editor writes, used when vanilla has no <c>plugins.js</c> at all.</summary>
    internal const string DefaultPrefix = "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n";

    internal const string DefaultSuffix = ";\n";

    private const string ListName = "$plugins";

    public static PluginListText Empty()
    {
        return new PluginListText(DefaultPrefix, new JArray(), DefaultSuffix);
    }

    public static bool TryParse(string? text, [NotNullWhen(true)] out PluginListText? list, [NotNullWhen(false)] out string? error)
    {
        list = null;
        if (text is null)
        {
            error = "no text";
            return false;
        }

        if (!TryFindListStart(text, out int start, out error))
        {
            return false;
        }

        int end = FindListEnd(text, start);
        if (end < 0)
        {
            error = "the list is not closed";
            return false;
        }

        string suffix = text[(end + 1)..];
        if (!IsPlainSuffix(suffix))
        {
            error = "something other than ; follows the list";
            return false;
        }

        try
        {
            if (MergeJson.Parse(text[start..(end + 1)]) is JArray entries)
            {
                list = new PluginListText(text[..start], entries, suffix);
                error = null;
                return true;
            }
        }
        catch (JsonReaderException exception)
        {
            error = $"the list is not valid JSON (line {exception.LineNumber}, position {exception.LinePosition})";
            return false;
        }

        error = "the list is not a JSON array";
        return false;
    }

    /// <summary>
    /// The <c>[</c> of the first <c>$plugins = [</c>, so a mention of the name in a comment before it is skipped.
    /// The error names what follows the first mention when no mention is the declaration.
    /// </summary>
    private static bool TryFindListStart(string text, out int start, [NotNullWhen(false)] out string? error)
    {
        start = -1;
        error = "it does not name " + ListName;
        bool first = true;
        for (int name = text.IndexOf(ListName, StringComparison.Ordinal);
             name >= 0;
             name = text.IndexOf(ListName, name + ListName.Length, StringComparison.Ordinal))
        {
            int position = SkipWhiteSpace(text, name + ListName.Length);
            string? problem = null;
            if (position >= text.Length || text[position] != '=')
            {
                problem = ListName + " is not followed by =";
            }
            else
            {
                position = SkipWhiteSpace(text, position + 1);
                if (position >= text.Length || text[position] != '[')
                {
                    problem = ListName + " is not set to a list";
                }
            }

            if (problem is null)
            {
                start = position;
                error = null;
                return true;
            }

            if (first)
            {
                error = problem;
                first = false;
            }
        }

        return false;
    }

    /// <summary>
    /// <c>[</c>, a line end, each entry compact, joined by <c>,</c> and a line end, a line end, <c>]</c>. The line
    /// end is the prefix's own, so a file the editor saved on Windows stays CRLF.
    /// </summary>
    public string Render()
    {
        if (Entries.Count == 0)
        {
            return Prefix + "[]" + Suffix;
        }

        string lineEnd = Prefix.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var builder = new StringBuilder(Prefix).Append('[').Append(lineEnd);
        for (int index = 0; index < Entries.Count; index++)
        {
            builder.Append(index == 0 ? "" : "," + lineEnd).Append(MergeJson.Write(Entries[index]));
        }

        return builder.Append(lineEnd).Append(']').Append(Suffix).ToString();
    }

    private static int SkipWhiteSpace(string text, int position)
    {
        while (position < text.Length && char.IsWhiteSpace(text[position]))
        {
            position++;
        }

        return position;
    }

    /// <summary>The index of the <c>]</c> that closes the list at <paramref name="start"/>, skipping brackets inside strings.</summary>
    private static int FindListEnd(string text, int start)
    {
        int depth = 0;
        bool inString = false;
        for (int position = start; position < text.Length; position++)
        {
            char current = text[position];
            if (inString)
            {
                if (current == '\\')
                {
                    position++;
                }
                else if (current == '"')
                {
                    inString = false;
                }
            }
            else if (current == '"')
            {
                inString = true;
            }
            else if (current is '[' or '{')
            {
                depth++;
            }
            else if (current is ']' or '}' && --depth == 0)
            {
                return current == ']' ? position : -1;
            }
        }

        return -1;
    }

    private static bool IsPlainSuffix(string suffix)
    {
        string rest = suffix.Trim();
        return rest.Length == 0 || rest == ";";
    }
}
