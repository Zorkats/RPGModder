using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace RPGModder.Tests.Support;

/// <summary>
/// Writes a minimal RPG Maker MV or MZ game folder with invented content in the shapes of a
/// default new project (TST-1, TST-2). Tests never read a real game install.
/// </summary>
public sealed class RpgProjectBuilder
{
    private readonly string _root;
    private readonly Dictionary<string, string> _dataFiles = new(StringComparer.OrdinalIgnoreCase);
    private readonly Dictionary<string, string> _contentFiles = new(StringComparer.OrdinalIgnoreCase);
    private readonly Dictionary<string, string> _saveFiles = new(StringComparer.OrdinalIgnoreCase);
    private readonly List<JObject> _plugins = new();
    private RpgEngine _engine = RpgEngine.MV;
    private bool _usesWww;

    public RpgProjectBuilder(string root)
    {
        _root = root;
    }

    public RpgProjectBuilder WithEngine(RpgEngine engine)
    {
        _engine = engine;
        return this;
    }

    public RpgProjectBuilder WithWwwLayout()
    {
        _usesWww = true;
        return this;
    }

    public RpgProjectBuilder WithDataFile(string fileName, string json)
    {
        _dataFiles[fileName] = json;
        return this;
    }

    public RpgProjectBuilder WithPlugin(
        string name,
        bool status = true,
        IDictionary<string, string>? parameters = null,
        string description = "")
    {
        _plugins.Add(PluginJson(name, status, parameters, description));
        return this;
    }

    public RpgProjectBuilder WithContentFile(string relativePath, string content)
    {
        _contentFiles[relativePath] = content;
        return this;
    }

    public RpgProjectBuilder WithSaveFile(string fileName, string content)
    {
        _saveFiles[fileName] = content;
        return this;
    }

    public RpgGame Build()
    {
        string contentRoot = _usesWww ? Path.Combine(_root, "www") : _root;
        var game = new RpgGame(_root, contentRoot, Path.Combine(_root, "Game.exe"), _engine, _usesWww);

        Directory.CreateDirectory(contentRoot);
        File.WriteAllBytes(game.ExecutablePath, [0x4D, 0x5A, 0x00, 0x00]);
        WriteText(game, EngineMarkerPath(), "// Engine marker for a test fixture.\n");
        WriteText(game, "js/main.js", "// Entry point of a test fixture.\n");
        WriteText(game, "js/plugins.js", PluginsJs(_plugins));
        WriteText(game, "index.html", IndexHtml);
        WriteText(game, "package.json", "{\"name\":\"\",\"main\":\"index.html\"}\n");

        Dictionary<string, string> dataFiles = DefaultDataFiles();
        foreach (KeyValuePair<string, string> file in _dataFiles)
        {
            dataFiles[file.Key] = file.Value;
        }

        foreach (KeyValuePair<string, string> file in dataFiles)
        {
            WriteText(game, "data/" + file.Key, file.Value);
        }

        foreach (KeyValuePair<string, string> file in _contentFiles)
        {
            WriteText(game, file.Key, file.Value);
        }

        foreach (KeyValuePair<string, string> file in _saveFiles)
        {
            WriteText(game, "save/" + file.Key, file.Value);
        }

        return game;
    }

    /// <summary>The plugins.js text RPG Maker writes for a list of entries.</summary>
    public static string PluginsJs(IReadOnlyList<JObject> plugins)
    {
        string entries = string.Join(",\n", plugins.Select(p => p.ToString(Formatting.None)));
        string body = plugins.Count == 0 ? "[\n]" : "[\n" + entries + "\n]";
        return "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n" + body + ";\n";
    }

    public static JObject PluginJson(
        string name,
        bool status,
        IDictionary<string, string>? parameters,
        string description)
    {
        var parameterObject = new JObject();
        foreach (KeyValuePair<string, string> parameter in parameters ?? new Dictionary<string, string>())
        {
            parameterObject[parameter.Key] = parameter.Value;
        }

        return new JObject
        {
            ["name"] = name,
            ["status"] = status,
            ["description"] = description,
            ["parameters"] = parameterObject
        };
    }

    private const string IndexHtml =
        "<!DOCTYPE html>\n<html>\n<head>\n<meta charset=\"UTF-8\">\n<title>Fixture</title>\n</head>\n" +
        "<body>\n<script type=\"text/javascript\" src=\"js/main.js\"></script>\n</body>\n</html>\n";

    private string EngineMarkerPath()
    {
        return _engine == RpgEngine.MZ ? "js/rmmz_core.js" : "js/rpg_core.js";
    }

    private static void WriteText(RpgGame game, string relativePath, string content)
    {
        string path = game.ContentFile(relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    private static Dictionary<string, string> DefaultDataFiles()
    {
        return new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            ["Actors.json"] = Database(
                Record(1, "Test Actor", new JObject { ["classId"] = 1, ["initialLevel"] = 1, ["maxLevel"] = 99, ["equips"] = new JArray(0, 0, 0, 0, 0) })),
            ["Classes.json"] = Database(Record(1, "Test Class", new JObject { ["expParams"] = new JArray(30, 20, 30, 30), ["learnings"] = new JArray() })),
            ["Skills.json"] = Database(
                Record(1, "Test Attack", new JObject { ["mpCost"] = 0, ["scope"] = 1 }),
                Record(2, "Test Guard", new JObject { ["mpCost"] = 0, ["scope"] = 11 })),
            ["Items.json"] = Database(Record(1, "Test Potion", new JObject { ["price"] = 50, ["consumable"] = true })),
            ["Weapons.json"] = Database(Record(1, "Test Sword", new JObject { ["price"] = 100, ["wtypeId"] = 1 })),
            ["Armors.json"] = Database(Record(1, "Test Shield", new JObject { ["price"] = 80, ["atypeId"] = 1 })),
            ["Enemies.json"] = Database(Record(1, "Test Slime", new JObject { ["exp"] = 10, ["gold"] = 5 })),
            ["Troops.json"] = Database(Record(1, "Test Slime*2", new JObject { ["members"] = new JArray(), ["pages"] = new JArray() })),
            ["States.json"] = Database(Record(1, "Test Knockout", new JObject { ["priority"] = 100 })),
            ["Animations.json"] = Database(Record(1, "Test Hit", new JObject())),
            ["Tilesets.json"] = Database(Record(1, "Test Field", new JObject { ["mode"] = 1, ["tilesetNames"] = new JArray() })),
            ["CommonEvents.json"] = Database(Record(1, "Test Common", new JObject { ["trigger"] = 0, ["switchId"] = 1, ["list"] = new JArray() })),
            ["System.json"] = new JObject
            {
                ["gameTitle"] = "Fixture Game",
                ["switches"] = new JArray("", "Test Switch"),
                ["variables"] = new JArray("", "Test Variable"),
                ["versionId"] = 1,
                ["locale"] = "en_US"
            }.ToString(Formatting.None),
            ["MapInfos.json"] = new JArray(
                JValue.CreateNull(),
                new JObject
                {
                    ["id"] = 1,
                    ["name"] = "MAP001",
                    ["parentId"] = 0,
                    ["order"] = 1,
                    ["expanded"] = false,
                    ["scrollX"] = 0,
                    ["scrollY"] = 0
                }).ToString(Formatting.None),
            ["Map001.json"] = new JObject
            {
                ["width"] = 2,
                ["height"] = 2,
                ["data"] = new JArray(0, 0, 0, 0),
                ["events"] = new JArray(JValue.CreateNull())
            }.ToString(Formatting.None)
        };
    }

    private static string Database(params JObject[] records)
    {
        var array = new JArray(JValue.CreateNull());
        foreach (JObject record in records)
        {
            array.Add(record);
        }

        return array.ToString(Formatting.None);
    }

    private static JObject Record(int id, string name, JObject fields)
    {
        var record = new JObject { ["id"] = id, ["name"] = name, ["note"] = "" };
        record.Merge(fields);
        return record;
    }
}
