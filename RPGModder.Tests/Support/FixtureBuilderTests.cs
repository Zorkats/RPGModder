using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using RPGModder.Core.Models;
using RPGModder.Core.Services;

namespace RPGModder.Tests.Support;

public sealed class FixtureBuilderTests : IDisposable
{
    private readonly TempDirectory _temp = new();

    public void Dispose()
    {
        _temp.Dispose();
    }

    [Fact]
    public void Build_Mv_IsDetectedAsMv()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("mv")).Build();

        DetectedGame? detected = new GameDetectorService().DetectGameAt(game.GameRoot);

        Assert.NotNull(detected);
        Assert.Equal(RpgMakerEngine.MV, detected.Engine);
        Assert.Equal(game.ExecutablePath, detected.ExePath);
    }

    [Fact]
    public void Build_MzWithWwwLayout_IsDetectedAsMz()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("mz")).WithEngine(RpgEngine.MZ).WithWwwLayout().Build();

        DetectedGame? detected = new GameDetectorService().DetectGameAt(game.GameRoot);

        Assert.NotNull(detected);
        Assert.Equal(RpgMakerEngine.MZ, detected.Engine);
    }

    [Fact]
    public void Build_WithWwwLayout_PutsContentUnderWww()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("www")).WithWwwLayout().Build();

        var engine = new ModEngine(game.ExecutablePath);

        Assert.True(game.UsesWww);
        Assert.True(engine.UsesWwwFolder);
        Assert.Equal(Path.Combine(game.GameRoot, "www"), engine.ContentPath);
        Assert.True(File.Exists(Path.Combine(game.GameRoot, "www", "data", "System.json")));
        Assert.True(File.Exists(Path.Combine(game.GameRoot, "Game.exe")));
    }

    [Fact]
    public void Build_WithoutWwwLayout_PutsContentAtRoot()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("flat")).Build();

        var engine = new ModEngine(game.ExecutablePath);

        Assert.False(engine.UsesWwwFolder);
        Assert.Equal(game.GameRoot, engine.ContentPath);
        Assert.True(File.Exists(Path.Combine(game.GameRoot, "data", "Actors.json")));
    }

    [Fact]
    public void Build_DataFiles_AreDatabaseArraysWithANullFirstElement()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("data")).Build();

        foreach (string file in new[] { "Actors", "Classes", "Skills", "Items", "Weapons", "Armors", "Enemies", "Troops", "States", "Animations", "Tilesets", "CommonEvents" })
        {
            JArray records = JArray.Parse(game.ReadContent("data/" + file + ".json"));
            Assert.Equal(JTokenType.Null, records[0].Type);
            Assert.Equal(1, (int)records[1]["id"]!);
        }

        Assert.Equal(1, (int)JObject.Parse(game.ReadContent("data/System.json"))["versionId"]!);
    }

    [Fact]
    public void WithDataFile_ReplacesTheDefaultFile()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("custom")).WithDataFile("Items.json", "[null]").Build();

        Assert.Equal("[null]", game.ReadContent("data/Items.json"));
    }

    [Fact]
    public void WithPlugin_WritesPluginsJsThatParsesBack()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("plugins"))
            .WithPlugin("FixtureCore", parameters: new Dictionary<string, string> { ["speed"] = "2" })
            .WithPlugin("FixtureExtra", status: false, description: "Second plugin")
            .Build();

        List<PluginEntry> plugins = ReadPlugins(game);

        Assert.StartsWith("// Generated by RPG Maker.\n", game.ReadContent("js/plugins.js"));
        Assert.Equal(new[] { "FixtureCore", "FixtureExtra" }, plugins.Select(p => p.Name));
        Assert.Equal("2", plugins[0].Parameters["speed"]);
        Assert.False(plugins[1].Status);
        Assert.Equal("Second plugin", plugins[1].Description);
    }

    [Fact]
    public void ModBuilder_ManifestRoundTripsAndSourcesExist()
    {
        string modFolder = new ModBuilder("fixture-mod")
            .WithName("Fixture mod")
            .ReplaceFile("data/Actors.json", "[null]")
            .PatchJson("data/System.json", new JObject { ["gameTitle"] = "Patched" })
            .RegisterPlugin("FixturePlugin")
            .AsFhmmMod()
            .BuildInto(_temp.Combine("mods"));

        ModManifest? manifest = JsonConvert.DeserializeObject<ModManifest>(File.ReadAllText(Path.Combine(modFolder, "mod.json")));

        Assert.NotNull(manifest);
        Assert.Equal("fixture-mod", manifest.Metadata.Id);
        Assert.Equal("Fixture mod", manifest.Metadata.Name);
        Assert.True(manifest.Metadata.IsFhmmMod);
        FileOperation op = Assert.Single(manifest.FileOps);
        Assert.Equal("data/Actors.json", op.Target);
        Assert.Equal("[null]", File.ReadAllText(Path.Combine(modFolder, op.Source)));
        Assert.Equal("Patched", (string)Assert.Single(manifest.JsonPatches).MergeData["gameTitle"]!);
        Assert.Equal("FixturePlugin", Assert.Single(manifest.PluginsRegistry).Name);
    }

    private static List<PluginEntry> ReadPlugins(RpgGame game)
    {
        string text = game.ReadContent("js/plugins.js");
        int start = text.IndexOf('[');
        int end = text.LastIndexOf(']');
        return JsonConvert.DeserializeObject<List<PluginEntry>>(text.Substring(start, end - start + 1))!;
    }
}
