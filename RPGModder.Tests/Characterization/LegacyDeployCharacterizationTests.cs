using LZStringCSharp;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using RPGModder.Core.Models;
using RPGModder.Core.Services;
using RPGModder.Tests.Support;
using RPGModder.Core.Workspace;

namespace RPGModder.Tests.Characterization;

// Records what the deploy path of 2.0.0 (ModEngine.RebuildGame) does today, before 2a replaces the
// merge engines (TST-3). A behaviour that must survive keeps its test; a behaviour that 2a removes
// (the FHMM state writes, FH-8) is changed in the same diff that removes it, so the change is visible.
public sealed class LegacyDeployCharacterizationTests : IDisposable
{
    private readonly TempDirectory _temp = new();

    public void Dispose()
    {
        _temp.Dispose();
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void Deploy_SingleModReplacingADataFile_WritesTheModBytes(bool useMerging)
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game")).Build();
        string vanilla = game.ReadContent("data/Actors.json");
        const string modded = "[null,{\"id\":1,\"name\":\"Replaced Actor\",\"note\":\"\"}]";
        var mod = new ModBuilder("replace-actors").ReplaceFile("data/Actors.json", modded);

        ModEngine engine = Prepare(game, useMerging, mod);
        AssertDeployed(engine.RebuildGame(Profile(mod)));

        Assert.Equal(modded, game.ReadContent("data/Actors.json"));
        Assert.Equal(vanilla, File.ReadAllText(Path.Combine(new GameWorkspacePaths(game.GameRoot).CleanBackup, "data", "Actors.json")));
    }

    [Fact]
    public void Deploy_AfterTheModIsDisabled_RestoresTheVanillaBytes()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game")).Build();
        string vanilla = game.ReadContent("data/Actors.json");
        var mod = new ModBuilder("replace-actors").ReplaceFile("data/Actors.json", "[null]");

        ModEngine engine = Prepare(game, true, mod);
        AssertDeployed(engine.RebuildGame(Profile(mod)));
        AssertDeployed(engine.RebuildGame(Profile()));

        Assert.Equal(vanilla, game.ReadContent("data/Actors.json"));
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void Deploy_PluginsRegistry_ReplacesByNameAndAppendsInRegistryOrder(bool useMerging)
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game"))
            .WithPlugin("FixtureAlpha", parameters: new Dictionary<string, string> { ["level"] = "1" })
            .WithPlugin("FixtureBeta")
            .Build();
        var mod = new ModBuilder("plugin-mod")
            .RegisterPlugin("FixtureAlpha", status: false, parameters: new Dictionary<string, string> { ["level"] = "2" })
            .RegisterPlugin("FixtureGamma", description: "Added by a mod");

        ModEngine engine = Prepare(game, useMerging, mod);
        AssertDeployed(engine.RebuildGame(Profile(mod)));

        string pluginsJs = game.ReadContent("js/plugins.js");
        List<PluginEntry> plugins = ParsePlugins(pluginsJs);
        Assert.StartsWith("// Generated by RPGModder\nvar $plugins =\n", pluginsJs);
        Assert.EndsWith("];\n", pluginsJs);
        Assert.Equal(new[] { "FixtureBeta", "FixtureAlpha", "FixtureGamma" }, plugins.Select(p => p.Name));
        Assert.False(plugins[1].Status);
        Assert.Equal("2", plugins[1].Parameters["level"]);
        Assert.Equal("Added by a mod", plugins[2].Description);
    }

    [Fact]
    public void Deploy_ConfigSaveFromTwoMods_IsMergedFieldByFieldIntoTheSaveFolder()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game"))
            .WithWwwLayout()
            .WithSaveFile("config.rpgsave", Lz(new JObject { ["alwaysDash"] = false, ["bgmVolume"] = 100, ["seVolume"] = 100 }))
            .Build();
        var dash = new ModBuilder("config-dash").ReplaceFile("save/config.rpgsave", Lz(new JObject { ["alwaysDash"] = true }));
        var volume = new ModBuilder("config-volume").ReplaceFile("save/config.rpgsave", Lz(new JObject { ["bgmVolume"] = 60 }));

        ModEngine engine = Prepare(game, true, dash, volume);
        AssertDeployed(engine.RebuildGame(Profile(dash, volume)));

        string written = File.ReadAllText(Path.Combine(game.GameRoot, "www", "save", "config.rpgsave"));
        JObject config = JObject.Parse(LZString.DecompressFromBase64(written));
        Assert.True((bool)config["alwaysDash"]!);
        Assert.Equal(60, (int)config["bgmVolume"]!);
        Assert.Equal(100, (int)config["seVolume"]!);
    }

    [Fact]
    public void Deploy_ConfigSaveFromTwoModsSettingOneField_LastModInLoadOrderWins()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game"))
            .WithSaveFile("config.rpgsave", Lz(new JObject { ["bgmVolume"] = 100 }))
            .Build();
        var quiet = new ModBuilder("config-quiet").ReplaceFile("save/config.rpgsave", Lz(new JObject { ["bgmVolume"] = 20 }));
        var loud = new ModBuilder("config-loud").ReplaceFile("save/config.rpgsave", Lz(new JObject { ["bgmVolume"] = 90 }));

        ModEngine engine = Prepare(game, true, quiet, loud);
        AssertDeployed(engine.RebuildGame(Profile(quiet, loud)));

        JObject config = JObject.Parse(LZString.DecompressFromBase64(File.ReadAllText(Path.Combine(game.SaveFolder, "config.rpgsave"))));
        Assert.Equal(90, (int)config["bgmVolume"]!);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void Deploy_JsonPatches_DeepMergeIntoTheTargetObject(bool useMerging)
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game"))
            .WithDataFile("System.json", "{\"gameTitle\":\"Fixture Game\",\"switches\":[\"\",\"Old\"],\"sounds\":{\"cursor\":\"a\",\"ok\":\"b\"},\"versionId\":1}")
            .Build();
        var title = new ModBuilder("patch-title").PatchJson("data/System.json", new JObject
        {
            ["gameTitle"] = "Patched Title",
            ["switches"] = new JArray("", "New", "Added"),
            ["sounds"] = new JObject { ["ok"] = "c" }
        });
        var flag = new ModBuilder("patch-flag").PatchJson("data/System.json", new JObject { ["fixtureFlag"] = true });

        ModEngine engine = Prepare(game, useMerging, title, flag);
        AssertDeployed(engine.RebuildGame(Profile(title, flag)));

        string text = game.ReadContent("data/System.json");
        JObject system = JObject.Parse(text);
        Assert.Equal("Patched Title", (string)system["gameTitle"]!);
        Assert.True(JToken.DeepEquals(new JArray("", "New", "Added"), system["switches"]));
        Assert.Equal("a", (string)system["sounds"]!["cursor"]!);
        Assert.Equal("c", (string)system["sounds"]!["ok"]!);
        Assert.True((bool)system["fixtureFlag"]!);
        Assert.Equal(1, (int)system["versionId"]!);
        Assert.Contains("  \"gameTitle\": \"Patched Title\"", text);
    }

    [Fact]
    public void Deploy_FhmmStyleMod_WritesANestedStateFileWithStatusTrue()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game")).WithWwwLayout().Build();
        var mod = new ModBuilder("FixtureLoaderMod")
            .ReplaceFile("mods/FixtureLoaderMod/FixtureLoaderMod.js", "// fixture mod script\n");

        ModEngine engine = Prepare(game, true, mod);
        AssertDeployed(engine.RebuildGame(Profile(mod)));

        string statePath = game.ContentFile("mods/FixtureLoaderMod/FixtureLoaderMod.json");
        Assert.True(File.Exists(statePath));
        JObject state = JObject.Parse(File.ReadAllText(statePath));
        Assert.Equal("FixtureLoaderMod", (string)state["name"]!);
        Assert.True((bool)state["status"]!);
        Assert.True((bool)state["danger"]!);
        Assert.Empty((JObject)state["parameters"]!);
    }

    [Fact]
    public void Deploy_FhmmStyleModShippingItsOwnState_ForcesStatusTrueAndKeepsTheRest()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game")).WithWwwLayout().Build();
        var mod = new ModBuilder("FixtureLoaderMod")
            .ReplaceFile("mods/FixtureLoaderMod/FixtureLoaderMod.js", "// fixture mod script\n")
            .ReplaceFile(
                "mods/FixtureLoaderMod/FixtureLoaderMod.json",
                "{\"name\":\"FixtureLoaderMod\",\"status\":false,\"parameters\":{\"speed\":3},\"danger\":false}");

        ModEngine engine = Prepare(game, true, mod);
        AssertDeployed(engine.RebuildGame(Profile(mod)));

        JObject state = JObject.Parse(game.ReadContent("mods/FixtureLoaderMod/FixtureLoaderMod.json"));
        Assert.True((bool)state["status"]!);
        Assert.False((bool)state["danger"]!);
        Assert.Equal(3, (int)state["parameters"]!["speed"]!);
    }

    [Fact]
    public void Deploy_ModFolderWithoutAMatchingScript_GetsNoFhmmStateFile()
    {
        RpgGame game = new RpgProjectBuilder(_temp.Combine("game")).WithWwwLayout().Build();
        var mod = new ModBuilder("FixtureAssets").ReplaceFile("mods/FixtureAssets/readme.txt", "assets only\n");

        ModEngine engine = Prepare(game, true, mod);
        AssertDeployed(engine.RebuildGame(Profile(mod)));

        Assert.False(File.Exists(game.ContentFile("mods/FixtureAssets/FixtureAssets.json")));
    }

    private static ModEngine Prepare(RpgGame game, bool useMerging, params ModBuilder[] mods)
    {
        var engine = new ModEngine(game.ExecutablePath) { UseMerging = useMerging };
        engine.InitializeSafeState();
        string modsRoot = new GameWorkspacePaths(game.GameRoot).Mods;
        foreach (ModBuilder mod in mods)
        {
            mod.BuildInto(modsRoot);
        }

        return engine;
    }

    private static ModProfile Profile(params ModBuilder[] mods)
    {
        List<string> ids = mods.Select(m => m.Id).ToList();
        return new ModProfile { EnabledMods = ids, LoadOrder = new List<string>(ids) };
    }

    private static void AssertDeployed(OperationResult result)
    {
        Assert.True(result.Success, string.Join("; ", result.Diagnostics.Select(d => d.Code + ": " + d.Message)));
    }

    private static string Lz(JObject config)
    {
        return LZString.CompressToBase64(config.ToString(Formatting.None));
    }

    private static List<PluginEntry> ParsePlugins(string pluginsJs)
    {
        int start = pluginsJs.IndexOf('[');
        int end = pluginsJs.LastIndexOf(']');
        return JsonConvert.DeserializeObject<List<PluginEntry>>(pluginsJs.Substring(start, end - start + 1))!;
    }
}
